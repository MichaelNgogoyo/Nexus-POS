-- Idempotent baseline for new installs and legacy POS schemas sharing a database with Keycloak.
CREATE TABLE IF NOT EXISTS audit_logs (
        id bigint generated by default as identity,
        timestamp timestamp(6) not null,
        action varchar(255) not null,
        actor varchar(255) not null,
        after_value varchar(255),
        before_value varchar(255),
        entity_id varchar(255),
        entity_type varchar(255),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS blogs (
        id bigint generated by default as identity,
        author varchar(255),
        body varchar(255),
        title varchar(255),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS cart (
        id bigint generated by default as identity,
        user_id bigint not null unique,
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS cart_item (
        quantity integer not null,
        cart_id bigint,
        cart_product bigint,
        id bigint generated by default as identity,
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS category (
        product_count integer not null,
        id bigint generated by default as identity,
        name varchar(255) not null unique,
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS combo_items (
        quantity integer,
        combo_id bigint not null,
        id bigint generated by default as identity,
        product_id bigint not null,
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS combos (
        active boolean,
        price numeric(38,2),
        id bigint generated by default as identity,
        description varchar(255),
        name varchar(255),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS customers (
        loyalty_points integer,
        total_spent numeric(38,2),
        created_at timestamp(6),
        id bigint generated by default as identity,
        last_visit_at timestamp(6),
        email varchar(255),
        name varchar(255) not null,
        notes varchar(255),
        phone varchar(255),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS expenses (
        amount numeric(38,2) not null,
        expense_date date not null,
        created_at timestamp(6),
        id bigint generated by default as identity,
        branch varchar(255),
        category varchar(255) not null check (category in ('RENT','SALARIES','ELECTRICITY','WATER','INTERNET','FUEL','MAINTENANCE','FOOD_SUPPLIES','MISCELLANEOUS')),
        created_by varchar(255),
        description varchar(255),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS kitchen_orders (
        completed_at timestamp(6),
        id bigint generated by default as identity,
        order_id bigint unique,
        received_at timestamp(6),
        started_at timestamp(6),
        notes varchar(255),
        status varchar(255) check (status in ('PENDING','PREPARING','READY','SERVED','CANCELLED')),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS modifier_groups (
        max_select integer,
        min_select integer,
        multi_select boolean,
        required boolean,
        id bigint generated by default as identity,
        product_id bigint,
        name varchar(255),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS modifiers (
        additional_price numeric(38,2),
        available boolean,
        group_id bigint not null,
        id bigint generated by default as identity,
        name varchar(255),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS order_item_modifiers (
        modifier_id bigint not null,
        order_item_id bigint not null,
        primary key (order_item_id, modifier_id)
    );
CREATE TABLE IF NOT EXISTS order_items (
        line_total numeric(38,2),
        quantity integer,
        unit_price numeric(38,2),
        id bigint generated by default as identity,
        order_id bigint not null,
        product_id bigint,
        kitchen_status varchar(255) check (kitchen_status in ('PENDING','PREPARING','READY','SERVED','CANCELLED')),
        notes varchar(255),
        product_name varchar(255),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS product (
        active boolean not null,
        discount float(53) not null,
        low_stock_threshold integer not null default 5,
        price numeric(19,2),
        quantity integer not null,
        reorder_level integer,
        reorder_quantity integer,
        category_id bigint,
        created_at timestamp(6) with time zone,
        id bigint generated by default as identity,
        updated_at timestamp(6) with time zone,
        barcode varchar(255) unique,
        imageurl varchar(255),
        name varchar(255),
        sku varchar(255) unique,
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS purchase_order_items (
        line_total numeric(38,2),
        ordered_quantity integer,
        received_quantity integer,
        unit_cost numeric(38,2),
        id bigint generated by default as identity,
        product_id bigint,
        purchase_order_id bigint not null,
        product_name varchar(255),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS purchase_orders (
        total_amount numeric(38,2),
        created_at timestamp(6),
        id bigint generated by default as identity,
        received_at timestamp(6),
        supplier_id bigint,
        created_by varchar(255),
        notes varchar(255),
        order_number varchar(255),
        status varchar(255) check (status in ('DRAFT','SENT','RECEIVED','CANCELLED')),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS reservations (
        guest_count integer,
        created_at timestamp(6),
        id bigint generated by default as identity,
        reservation_time timestamp(6) not null,
        table_id bigint,
        customer_name varchar(255),
        customer_phone varchar(255),
        notes varchar(255),
        status varchar(255) not null check (status in ('PENDING','CONFIRMED','SEATED','COMPLETED','CANCELLED','NO_SHOW')),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS restaurant_orders (
        discount_amount numeric(38,2),
        service_charge_amount numeric(19,2),
        subtotal numeric(38,2),
        tax_amount numeric(38,2),
        total numeric(38,2),
        created_at timestamp(6),
        id bigint generated by default as identity,
        sale_id bigint unique,
        table_id bigint,
        updated_at timestamp(6),
        idempotency_key varchar(64) unique,
        cashier_id varchar(255),
        customer_name varchar(255),
        notes varchar(255),
        order_number varchar(255) not null unique,
        order_type varchar(255) check (order_type in ('DINE_IN','TAKEAWAY','DELIVERY','ROOM_CHARGE')),
        room_number varchar(255),
        status varchar(255) check (status in ('OPEN','KITCHEN','READY','COMPLETED','PAID','CANCELLED','REFUNDED')),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS restaurant_tables (
        capacity integer,
        id bigint generated by default as identity,
        occupied_at timestamp(6),
        floor varchar(255),
        name varchar(255) not null,
        status varchar(255) not null check (status in ('AVAILABLE','OCCUPIED','RESERVED','CLEANING')),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS sale_item_modifiers (
        modifier_id bigint not null,
        sale_item_id bigint not null,
        primary key (sale_item_id, modifier_id)
    );
CREATE TABLE IF NOT EXISTS sale_item (
        price numeric(19,2) not null,
        quantity integer not null,
        id bigint generated by default as identity,
        product_id bigint not null,
        sale_id bigint not null,
        notes varchar(250),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS sales (
        amount_tendered numeric(19,2) not null,
        change_given numeric(19,2) not null,
        service_charge_amount numeric(19,2) not null,
        subtotal_amount numeric(19,2) not null,
        tax_amount numeric(19,2) not null,
        total_amount numeric(19,2) not null,
        created_at timestamp(6),
        id bigint generated by default as identity,
        restaurant_order_id bigint,
        table_id bigint,
        room_number varchar(24),
        order_number varchar(32),
        order_type varchar(32) check (order_type in ('DINE_IN','TAKEAWAY','DELIVERY','ROOM_CHARGE')),
        idempotency_key varchar(64) unique,
        guest_name varchar(120),
        notes varchar(500),
        cashier_id varchar(255),
        payment_method varchar(255),
        status varchar(255) check (status in ('COMPLETED','RETURNED','VOIDED')),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS shifts (
        closing_balance numeric(38,2),
        expected_balance numeric(38,2),
        opening_balance numeric(38,2),
        variance numeric(38,2),
        closed_at timestamp(6),
        id bigint generated by default as identity,
        opened_at timestamp(6),
        cashier_id varchar(255),
        cashier_name varchar(255),
        notes varchar(255),
        status varchar(255) check (status in ('OPEN','CLOSED')),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS stock_movements (
        balance_after integer not null,
        delta integer not null,
        created_at timestamp(6),
        id bigint generated by default as identity,
        product_id bigint not null,
        reason varchar(255),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS suppliers (
        active boolean,
        id bigint generated by default as identity,
        address varchar(255),
        contact_name varchar(255),
        email varchar(255),
        name varchar(255) not null,
        phone varchar(255),
        primary key (id)
    );
CREATE TABLE IF NOT EXISTS user_roles (
        user_id bigint not null,
        roles varchar(255) check (roles in ('ROLE_USER','ROLE_ADMIN'))
    );
CREATE TABLE IF NOT EXISTS users (
        id bigint generated by default as identity,
        email varchar(255) not null unique,
        keycloak_id varchar(255) unique,
        password varchar(255) not null,
        username varchar(255) not null unique,
        primary key (id)
    );

