CREATE TABLE IF NOT EXISTS cash_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT NOT NULL REFERENCES shifts(id),
    type VARCHAR(16) NOT NULL CHECK (type IN ('CASH_IN', 'CASH_OUT', 'CASH_REFUND')),
    amount NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    reason VARCHAR(300) NOT NULL CHECK (length(trim(reason)) > 0),
    sale_id BIGINT UNIQUE REFERENCES sales(id),
    idempotency_key VARCHAR(80) NOT NULL UNIQUE,
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_cash_movements_shift_created_at ON cash_movements (shift_id, created_at, id);

ALTER TABLE sales ADD COLUMN IF NOT EXISTS shift_id BIGINT REFERENCES shifts(id);

CREATE UNIQUE INDEX IF NOT EXISTS uk_shifts_one_open_per_cashier
    ON shifts (cashier_id) WHERE status = 'OPEN';
